//! Шаблон txt-отчёта и подстановка значений вместо плейсхолдеров.

/// Шаблон отчёта. Все динамические значения — в виде {{PLACEHOLDER}}.
/// Сюда НИЧЕГО не подставляем вручную, только через `fill_template`.
pub const REPORT_TEMPLATE: &str = r#"=================================================
              ОТЧЕТ О ПОСЕЩАЕМОСТИ БАССЕЙНА
Период: {{PERIOD_START}} - {{PERIOD_END}}
Дата формирования: {{GENERATED_AT}}
=================================================

ОБЩАЯ СТАТИСТИКА
-------------------------------------------------
Всего посещений: {{TOTAL_VISITS}}
Уникальных посетителей: {{UNIQUE_CLIENTS}}
Среднее посещений в день: {{AVG_PER_DAY}}
Пиковый день: {{PEAK_DAY}} ({{PEAK_DAY_VISITS}} посещений)

РАСПРЕДЕЛЕНИЕ ПО ТИПАМ АБОНЕМЕНТОВ
-------------------------------------------------
Разовый: {{CNT_ONCE_ONLY}} ({{PCT_ONCE_ONLY}}%)
Абонемент 4 посещения: {{CNT_VISIT4}} ({{PCT_VISIT4}}%)
Абонемент 8 посещений: {{CNT_VISIT8}} ({{PCT_VISIT8}}%)
Абонемент 12 посещений: {{CNT_VISIT12}} ({{PCT_VISIT12}}%)
Безлимит: {{CNT_NO_LIMIT}} ({{PCT_NO_LIMIT}}%)

ТОП-{{TOP_LIMIT}} АКТИВНЫХ КЛИЕНТОВ
-------------------------------------------------
{{TOP_CLIENTS}}

ПОСЕЩЕНИЯ ПО ДНЯМ
-------------------------------------------------
{{VISITS_BY_DAY}}

=================================================
              Конец отчета
=================================================
"#;

/// Подставить значение в шаблон. Если плейсхолдера нет — noop (не падаем).
pub fn put(template: &str, placeholder: &str, value: impl ToString) -> String {
    template.replace(&format!("{{{{{placeholder}}}}}"), &value.to_string())
}
